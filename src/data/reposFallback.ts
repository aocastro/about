export function categorizeRepo(repo: Pick<GitHubRepo, 'name' | 'description'>): Exclude<RepoCategory, 'all'> {
  const haystack = `${repo.name} ${repo.description ?? ''}`.toLowerCase();

  if (RESEARCH_KEYWORDS.some((kw) => haystack.includes(kw))) {
    return 'research';
  }
  if (EDUCATION_KEYWORDS.some((kw) => haystack.includes(kw))) {
    return 'education';
  }
  return 'apps';
}

